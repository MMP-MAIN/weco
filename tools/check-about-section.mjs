import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = file => readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
const html = read('index.html');
const css = read('studio-refresh.css');
const js = read('studio-refresh.js');
const about = html.match(/<section class="studio-about"[\s\S]*?<\/section>/)?.[0];
assert.ok(about, 'An independent company introduction exists.');
assert.match(about, /id="weco-about" aria-labelledby="wecoAboutTitle" tabindex="-1"/);
assert.match(about, /브랜드의 가능성을 찾고/);
assert.match(about, /사업의 방향을 세우고 브랜드와 공간으로 구체화하는 기획 회사/);
assert.match(about, /위코가 지향하는 가치입니다/);
assert.doesNotMatch(about, /부동산 가격|수익 보장|주거 인테리어|heroHeadline|hero-promise|<img/);
assert.ok(html.indexOf(about) < html.indexOf('id="portfolio-preview"'));
assert.match(html, /href="#weco-about">About \/ 위코 소개/);
assert.match(html, /id="scope" tabindex="-1"/);
assert.match(html, /id="intelligence"/);
assert.doesNotMatch(html, /OUR APPROACH|감각은 선명하게/);
assert.match(html, /class="container studio-resources-grid"/);
assert.match(html, /data-conversion="marketing_site"/);
assert.match(html, /data-conversion="brand_discovery"/);
assert.match(html, /studio-refresh\.css\?v=3/);
assert.match(html, /studio-refresh\.js\?v=3/);
assert.match(js, /href === '#weco-about'/);
assert.match(css, /\.studio-about-grid\{display:grid;grid-template-columns:minmax\(0,1\.15fr\) minmax\(0,1fr\)/);
assert.match(css, /\.studio-about-grid,.*\{grid-template-columns:1fr/);
assert.match(css, /\.studio-about-copy\{[^}]*overflow-wrap:anywhere/);
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'IDs remain unique.');
console.log('PASS: independent About section, positioning, compact resources, menu focus, responsive rules, unique IDs and preserved destinations.');
